function seedTaxonomySqlite(db) {
    const insertCat = db.prepare(`
        INSERT INTO magazine_categories (name, slug, parent_id, sort_order)
        VALUES (?, ?, ?, ?)
        ON CONFLICT(slug) DO UPDATE SET name = excluded.name
    `);
    const getCat = db.prepare('SELECT id FROM magazine_categories WHERE slug = ?');
    CATEGORY_TREE_WALK(seed.CATEGORY_TREE, null, (node, parentId, order) => {
        insertCat.run(node.name, node.slug, parentId, order);
        const row = getCat.get(node.slug);
        return row ? Number(row.id) : null;
    });
    const insertTag = db.prepare(`
        INSERT INTO magazine_tags (name, slug) VALUES (?, ?)
        ON CONFLICT(slug) DO UPDATE SET name = excluded.name
    `);
    seed.TAGS.forEach((tag) => insertTag.run(tag.name, tag.slug));
    const insertAuthor = db.prepare(`
        INSERT INTO magazine_authors (first_name, last_name, slug, specialty, bio, photo_url)
        VALUES (?, ?, ?, ?, ?, ?)
        ON CONFLICT(slug) DO UPDATE SET
            first_name = excluded.first_name,
            last_name = excluded.last_name,
            specialty = excluded.specialty,
            bio = excluded.bio
    `);
    const colors = ['#0f766e', '#0d9488', '#115e59'];
    seed.AUTHORS.forEach((author, index) => {
        const photo = placeholderImage(`magazine-author-${author.slug}.svg`, author.firstName, colors[index % colors.length]);
        insertAuthor.run(author.firstName, author.lastName, author.slug, author.specialty, author.bio, photo);
    });
    const editorial = db.prepare('SELECT id FROM magazine_authors WHERE slug = ?').get('tatkids-editorial');
    const admin = db.prepare('SELECT id FROM users WHERE is_admin = 1 ORDER BY id LIMIT 1').get();
    if (editorial && admin) {
        db.prepare('UPDATE magazine_authors SET user_id = ? WHERE id = ?').run(admin.id, editorial.id);
    }
}

async function seedTaxonomyPg(q, one) {
    const walk = async (nodes, parentId) => {
        for (let i = 0; i < nodes.length; i += 1) {
            const node = nodes[i];
            await q(
                `INSERT INTO magazine_categories (name, slug, parent_id, sort_order)
                 VALUES ($1,$2,$3,$4)
                 ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name`,
                [node.name, node.slug, parentId, i]
            );
            const row = await one('SELECT id FROM magazine_categories WHERE slug = $1', [node.slug]);
            if (node.children && node.children.length) await walk(node.children, Number(row.id));
        }
    };
    await walk(seed.CATEGORY_TREE, null);
    for (const tag of seed.TAGS) {
        await q(
            `INSERT INTO magazine_tags (name, slug) VALUES ($1,$2)
             ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name`,
            [tag.name, tag.slug]
        );
    }
    const colors = ['#0f766e', '#0d9488', '#115e59'];
    for (let i = 0; i < seed.AUTHORS.length; i += 1) {
        const author = seed.AUTHORS[i];
        const photo = placeholderImage(`magazine-author-${author.slug}.svg`, author.firstName, colors[i % colors.length]);
        await q(
            `INSERT INTO magazine_authors (first_name, last_name, slug, specialty, bio, photo_url)
             VALUES ($1,$2,$3,$4,$5,$6)
             ON CONFLICT (slug) DO UPDATE SET
                first_name = EXCLUDED.first_name,
                last_name = EXCLUDED.last_name,
                specialty = EXCLUDED.specialty,
                bio = EXCLUDED.bio`,
            [author.firstName, author.lastName, author.slug, author.specialty, author.bio, photo]
        );
    }
    const editorial = await one('SELECT id FROM magazine_authors WHERE slug = $1', ['tatkids-editorial']);
    const admin = await one('SELECT id FROM users WHERE is_admin = 1 ORDER BY id LIMIT 1');
    if (editorial && admin) {
        await q('UPDATE magazine_authors SET user_id = $1 WHERE id = $2', [admin.id, editorial.id]);
    }
}

function CATEGORY_TREE_WALK(nodes, parentId, visit) {
    nodes.forEach((node, index) => {
        const id = visit(node, parentId, index);
        if (node.children && node.children.length) CATEGORY_TREE_WALK(node.children, id, visit);
    });
}

function tagIdsForPostSqlite(db, type, title, categorySlug) {
    const wanted = [];
    if (/خواب|نوزاد/.test(title)) wanted.push('sleep', 'newborn');
    if (/تغذیه|آهن|میان‌وعده|غذا/.test(title)) wanted.push('child-nutrition', 'brain-development');
    if (/اضطراب|تربیت|اجتماعی|قشقرق/.test(title)) wanted.push('anxiety');
    if (/بازی|مهارت/.test(title)) wanted.push('play');
    if (/سرماخوردگی|تب|بیماری/.test(title)) wanted.push('safety');
    if (type === 'video') wanted.push('play');
    if (categorySlug === 'nutrition') wanted.push('child-nutrition');
    const slugs = [...new Set(wanted.length ? wanted : ['play'])];
    return slugs.map((slug) => {
        const row = db.prepare('SELECT id FROM magazine_tags WHERE slug = ?').get(slug);
        return row ? Number(row.id) : null;
    }).filter(Boolean);
}

