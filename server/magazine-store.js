function nestComments(flat) {
    const byId = new Map();
    flat.forEach((item) => byId.set(item.id, { ...item, replies: [] }));
    const roots = [];
    byId.forEach((item) => {
        if (item.parentId && byId.has(item.parentId)) byId.get(item.parentId).replies.push(item);
        else roots.push(item);
    });
    return roots;
}

function buildCategoryTree(rows) {
    const items = rows.map(mapCategory);
    const byId = new Map(items.map((item) => [item.id, { ...item, children: [] }]));
    const roots = [];
    byId.forEach((item) => {
        if (item.parentId && byId.has(item.parentId)) byId.get(item.parentId).children.push(item);
        else roots.push(item);
    });
    const sortFn = (a, b) => a.sortOrder - b.sortOrder || a.id - b.id;
    const sortTree = (nodes) => {
        nodes.sort(sortFn);
        nodes.forEach((node) => sortTree(node.children));
    };
    sortTree(roots);
    return roots;
}

function uniqueSlugSqlite(db, table, slug, exceptId) {
    let candidate = slug;
    let n = 2;
    while (true) {
        const row = exceptId
            ? db.prepare(`SELECT id FROM ${table} WHERE slug = ? AND id != ?`).get(candidate, exceptId)
            : db.prepare(`SELECT id FROM ${table} WHERE slug = ?`).get(candidate);
        if (!row) return candidate;
        candidate = `${slug}-${n}`;
        n += 1;
    }
}

async function uniqueSlugPg(one, table, slug, exceptId) {
    let candidate = slug;
    let n = 2;
    while (true) {
        const row = exceptId
            ? await one(`SELECT id FROM ${table} WHERE slug = $1 AND id != $2`, [candidate, exceptId])
            : await one(`SELECT id FROM ${table} WHERE slug = $1`, [candidate]);
        if (!row) return candidate;
        candidate = `${slug}-${n}`;
        n += 1;
    }
}

