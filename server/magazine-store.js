function filterHydratedPosts(posts, filters = {}) {
    let list = posts.slice();
    if (filters.published !== false && !filters.includeUnpublished) {
        list = list.filter((post) => post.published);
    }
    if (filters.type) list = list.filter((post) => post.type === filters.type);
    if (filters.featured) list = list.filter((post) => post.featured);
    if (filters.categorySlug) {
        const match = list.find((post) => post.category && post.category.slug === filters.categorySlug);
        const parentId = match && match.category ? match.category.id : null;
        list = list.filter((post) => post.category && (
            post.category.slug === filters.categorySlug || post.category.parentId === parentId
        ));
    }
    if (filters.tagSlug) list = list.filter((post) => (post.tags || []).some((tag) => tag.slug === filters.tagSlug));
    if (filters.authorSlug) list = list.filter((post) => (post.authors || []).some((author) => author.slug === filters.authorSlug));
    if (filters.q) {
        const qtext = String(filters.q).toLowerCase();
        list = list.filter((post) => `${post.title} ${post.summary} ${post.content}`.toLowerCase().includes(qtext));
    }
    if (filters.sort === 'popular') list.sort((a, b) => b.viewCount - a.viewCount);
    else if (filters.featured) list.sort((a, b) => a.featuredOrder - b.featuredOrder);
    else list.sort((a, b) => String(b.createdAt || '').localeCompare(String(a.createdAt || '')));
    return list;
}

