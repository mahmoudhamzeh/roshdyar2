function rewriteHeroLinksSqlite(db) {
    const banners = db.prepare("SELECT id, link FROM magazine_banners WHERE link LIKE '/news/%'").all();
    banners.forEach((banner) => {
        const slug = String(banner.link || '').replace(/^\/news\//, '');
        if (!slug || /^\d+$/.test(slug)) return;
        const post = db.prepare('SELECT id FROM magazine_posts WHERE slug = ?').get(slug);
        if (post) {
            db.prepare('UPDATE magazine_banners SET link = ? WHERE id = ?').run(`/news/${post.id}`, banner.id);
        }
    });
}

async function rewriteHeroLinksPg(q, one, many) {
    const banners = await many("SELECT id, link FROM magazine_banners WHERE link LIKE '/news/%'");
    for (const banner of banners) {
        const slug = String(banner.link || '').replace(/^\/news\//, '');
        if (!slug || /^\d+$/.test(slug)) continue;
        const post = await one('SELECT id FROM magazine_posts WHERE slug = $1', [slug]);
        if (post) {
            await q('UPDATE magazine_banners SET link = $1 WHERE id = $2', [`/news/${post.id}`, banner.id]);
        }
    }
}

async function runSqlBatch(q, sql) {
    const statements = String(sql)
        .split(';')
        .map((part) => part.trim())
        .filter((part) => part.length > 0);
    for (const statement of statements) {
        await q(statement);
    }
}

