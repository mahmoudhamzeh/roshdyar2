function asBool(value) {
    return value === 1 || value === true || value === '1' || value === 't' || value === 'true';
}

function parseJson(value, fallback) {
    if (value == null || value === '') return fallback;
    if (typeof value === 'object') return value;
    try {
        return JSON.parse(value);
    } catch (_) {
        return fallback;
    }
}

