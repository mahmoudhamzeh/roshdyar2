function backfillSqlite(db) {
    const vendor = db.prepare('SELECT * FROM shop_vendors WHERE slug = ?').get(INTERNAL_VENDOR.slug);
    if (!vendor) return;
    db.prepare(`
        INSERT INTO shop_offers (product_id, vendor_id, price, stock, status)
        SELECT p.id, ?, p.price, p.stock, 'active'
        FROM products p
        WHERE NOT EXISTS (
            SELECT 1 FROM shop_offers o WHERE o.product_id = p.id AND o.vendor_id = ?
        )
    `).run(vendor.id, vendor.id);

    const products = db.prepare('SELECT id, category FROM products').all();
    const skillBySlug = new Map(
        db.prepare('SELECT * FROM shop_skills').all().map((row) => [row.slug, row])
    );
    const insertMeta = db.prepare(`
        INSERT OR IGNORE INTO shop_product_meta (product_id, age_band)
        VALUES (?, ?)
    `);
    const insertSkill = db.prepare(`
        INSERT OR IGNORE INTO shop_product_skills (product_id, skill_id, impact)
        VALUES (?, ?, 1)
    `);
    products.forEach((product) => {
        const defaults = CATEGORY_DEFAULTS[product.category] || { ageBand: '1-3', skills: ['cognitive'] };
        insertMeta.run(product.id, defaults.ageBand);
        defaults.skills.forEach((slug) => {
            const skill = skillBySlug.get(slug);
            if (skill) insertSkill.run(product.id, skill.id);
        });
    });
}

function ensureShopSchemaSqlite(db) {
    db.exec(SHOP_TABLES_SQLITE);
    if (!sqliteHasColumn(db, 'product_comments', 'rating')) {
        db.exec('ALTER TABLE product_comments ADD COLUMN rating INTEGER');
    }
    if (!sqliteHasColumn(db, 'product_comments', 'status')) {
        db.exec("ALTER TABLE product_comments ADD COLUMN status TEXT NOT NULL DEFAULT 'approved'");
    }
    if (!sqliteHasColumn(db, 'product_categories', 'active')) {
        db.exec('ALTER TABLE product_categories ADD COLUMN active INTEGER NOT NULL DEFAULT 1');
    }
    [
        ['offer_id', 'INTEGER'],
        ['vendor_id', 'INTEGER'],
        ['vendor_name', 'TEXT'],
        ['commission_pct', 'REAL'],
        ['commission_amount', 'REAL'],
        ['line_status', "TEXT DEFAULT 'pending'"]
    ].forEach(([col, type]) => {
        if (!sqliteHasColumn(db, 'order_items', col)) {
            db.exec(`ALTER TABLE order_items ADD COLUMN ${col} ${type}`);
        }
    });
    [
        ['person_kind', "TEXT DEFAULT 'individual'"],
        ['national_id', 'TEXT'],
        ['legal_name', 'TEXT'],
        ['registration_no', 'TEXT'],
        ['economic_code', 'TEXT'],
        ['owner_name', 'TEXT'],
        ['province', 'TEXT'],
        ['city', 'TEXT'],
        ['address', 'TEXT'],
        ['bank_name', 'TEXT'],
        ['bank_sheba', 'TEXT'],
        ['bank_account', 'TEXT']
    ].forEach(([col, type]) => {
        if (!sqliteHasColumn(db, 'shop_vendors', col)) {
            db.exec(`ALTER TABLE shop_vendors ADD COLUMN ${col} ${type}`);
        }
    });
    if (!sqliteHasColumn(db, 'products', 'review_status')) {
        db.exec("ALTER TABLE products ADD COLUMN review_status TEXT NOT NULL DEFAULT 'approved'");
    }
    seedDefaultsSqlite(db);
    backfillSqlite(db);
    seedShopExtrasSqlite(db);
}

