function loadSkillsForProductsSqlite(db, products) {
    if (!products.length) return products;
    const ids = products.map((p) => p.id);
    const placeholders = ids.map(() => '?').join(',');
    const rows = db.prepare(`
        SELECT ps.product_id, ps.impact, s.id, s.slug, s.title
        FROM shop_product_skills ps
        JOIN shop_skills s ON s.id = ps.skill_id
        WHERE ps.product_id IN (${placeholders})
    `).all(...ids);
    return attachSkillsToProducts(products, rows);
}

function listCatalogSqlite(db, asBool, filters, options) {
    const tree = categoryTreeFromRows(db.prepare('SELECT id, name, parent_id FROM product_categories').all());
    const { sql, params } = buildCatalogSql(withCategoryDescendants(filters, tree), options);
    const rows = db.prepare(sql).all(...params).map((row) => mapCatalogRow(row, asBool));
    return loadSkillsForProductsSqlite(db, rows);
}

function enrichProductSqlite(db, asBool, product) {
    if (!product) return null;
    const rows = listCatalogSqlite(db, asBool, {}, { activeOnly: false }).filter((row) => row.id === product.id);
    const catalog = rows[0] || product;
    return {
        ...product,
        ...catalog,
        images: product.images,
        comments: product.comments
    };
}

