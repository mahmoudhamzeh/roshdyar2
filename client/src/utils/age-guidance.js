export const getAgeInMonths = (birthDate) => {
    if (!birthDate) return 0;
    const birth = new Date(String(birthDate).replace(/\//g, '-'));
    if (Number.isNaN(birth.getTime())) return 0;
    const now = new Date();
    let months = (now.getFullYear() - birth.getFullYear()) * 12;
    months += now.getMonth() - birth.getMonth();
    if (now.getDate() < birth.getDate()) months -= 1;
    return Math.max(0, months);
};

export const formatAgeLabel = (months) => {
    const years = Math.floor(months / 12);
    const rem = months % 12;
    if (years <= 0) return `${months} ماهه`;
    if (rem === 0) return `${years} ساله`;
    return `${years} سال و ${rem} ماه`;
};

export const getGuidanceForAgeMonths = (months) => {
    const band =
        AGE_GUIDANCE_BANDS.find((b) => months >= b.minMonths && months <= b.maxMonths) ||
        AGE_GUIDANCE_BANDS[AGE_GUIDANCE_BANDS.length - 1];
    return band;
};

export const personalizeGuidanceNotes = (child, band) => {
    const notes = [];
    if (!child || !band) return notes;

    const allergies = child.allergies;
    const hasAllergyObject =
        allergies &&
        allergies.types &&
        Object.values(allergies.types).some(Boolean);
    const hasAllergyText = typeof allergies === 'string' && allergies.trim();

    if (hasAllergyObject || hasAllergyText) {
        notes.push(
            'با توجه به آلرژی ثبت‌شده، هر توصیه غذایی را با وضعیت آلرژی کودک تطبیق دهید و در صورت تردید با پزشک مشورت کنید.'
        );
    }

    if (child.special_illnesses) {
        const illnessObj =
            child.special_illnesses.types &&
            Object.values(child.special_illnesses.types).some(Boolean);
        const illnessText =
            typeof child.special_illnesses === 'string' && child.special_illnesses.trim();
        if (illnessObj || illnessText) {
            notes.push(
                'به‌خاطر شرایط خاص پزشکی ثبت‌شده، قبل از تغییر جدی در تغذیه یا فعالیت بدنی با پزشک معالج هماهنگ کنید.'
            );
        }
    }

    if (child.gender === 'girl' && band.minMonths >= 96) {
        notes.push('گفت‌وگوی آرام درباره تغییرات بدن و بلوغ را با زبان مناسب سن او آغاز کنید.');
    }
    if (child.gender === 'boy' && band.minMonths >= 96) {
        notes.push('درباره تغییرات بدن، ورزش و مدیریت هیجان با او فضای گفت‌وگوی امن بسازید.');
    }

    return notes;
};
